// Turns a pixel-art PNG into the grid Faro draws in the terminal: `node scripts/logo.mjs assets/faro.png`.
// It finds the art's blocks (runs of equal color), crops the background around them, and writes
// packages/faro/src/logo-pixels.ts: one row per block row, a hex color per block or null for background.
// Only 8-bit, non-interlaced RGB or RGBA PNGs, which is what screenshots and pixel editors write.
import { readFileSync, writeFileSync } from "node:fs";
import { inflateSync } from "node:zlib";

function decodePng(buf) {
	if (buf.readUInt32BE(0) !== 0x89504e47) throw new Error("not a PNG");
	let pos = 8;
	let width = 0;
	let height = 0;
	let channels = 0;
	const idat = [];
	while (pos < buf.length) {
		const len = buf.readUInt32BE(pos);
		const type = buf.toString("ascii", pos + 4, pos + 8);
		const data = buf.subarray(pos + 8, pos + 8 + len);
		if (type === "IHDR") {
			width = data.readUInt32BE(0);
			height = data.readUInt32BE(4);
			const depth = data[8];
			const color = data[9];
			if (depth !== 8 || data[12] !== 0) throw new Error("only 8-bit, non-interlaced PNGs");
			channels = color === 6 ? 4 : color === 2 ? 3 : 0;
			if (!channels) throw new Error("only RGB or RGBA PNGs");
		} else if (type === "IDAT") idat.push(data);
		pos += 12 + len;
	}
	const raw = inflateSync(Buffer.concat(idat));
	const stride = width * channels;
	const out = Buffer.alloc(height * stride);
	for (let y = 0; y < height; y++) {
		const filter = raw[y * (stride + 1)];
		for (let x = 0; x < stride; x++) {
			const v = raw[y * (stride + 1) + 1 + x];
			const a = x >= channels ? out[y * stride + x - channels] : 0;
			const b = y > 0 ? out[(y - 1) * stride + x] : 0;
			const c = x >= channels && y > 0 ? out[(y - 1) * stride + x - channels] : 0;
			let p = 0;
			if (filter === 1) p = a;
			else if (filter === 2) p = b;
			else if (filter === 3) p = (a + b) >> 1;
			else if (filter === 4) {
				const pa = Math.abs(b - c);
				const pb = Math.abs(a - c);
				const pc = Math.abs(a + b - 2 * c);
				p = pa <= pb && pa <= pc ? a : pb <= pc ? b : c;
			}
			out[y * stride + x] = (v + p) & 0xff;
		}
	}
	const at = (x, y) => {
		const i = y * stride + x * channels;
		return (out[i] << 16) | (out[i + 1] << 8) | out[i + 2];
	};
	return { width, height, at };
}

/** Positions where the color changes along one axis, anywhere across the other. */
function edges(n, m, differs) {
	const cuts = [0];
	for (let i = 1; i < n; i++) {
		for (let j = 0; j < m; j++) {
			if (differs(i, j)) {
				cuts.push(i);
				break;
			}
		}
	}
	cuts.push(n);
	return cuts;
}

/** The block size: the most common distance between color changes, so anti-aliased edges are ignored. */
function blockSize(cuts) {
	const counts = new Map();
	for (let i = 1; i < cuts.length; i++) {
		const d = cuts[i] - cuts[i - 1];
		if (d > 4) counts.set(d, (counts.get(d) ?? 0) + 1);
	}
	let best = 1;
	let max = 0;
	for (const [d, c] of counts) if (c > max || (c === max && d < best)) [best, max] = [d, c];
	return best;
}

const file = process.argv[2] ?? "assets/faro.png";
const img = decodePng(readFileSync(file));
const bg = img.at(0, 0);
const near = (a, b) =>
	Math.abs((a >> 16) - (b >> 16)) + Math.abs(((a >> 8) & 255) - ((b >> 8) & 255)) + Math.abs((a & 255) - (b & 255)) <
	24;
let x0 = img.width;
let y0 = img.height;
let x1 = 0;
let y1 = 0;
for (let y = 0; y < img.height; y++)
	for (let x = 0; x < img.width; x++)
		if (!near(img.at(x, y), bg)) {
			x0 = Math.min(x0, x);
			y0 = Math.min(y0, y);
			x1 = Math.max(x1, x);
			y1 = Math.max(y1, y);
		}
const size = Math.min(
	blockSize(edges(x1 - x0 + 1, y1 - y0 + 1, (i, j) => !near(img.at(x0 + i, y0 + j), img.at(x0 + i - 1, y0 + j)))),
	blockSize(edges(y1 - y0 + 1, x1 - x0 + 1, (i, j) => !near(img.at(x0 + j, y0 + i), img.at(x0 + j, y0 + i - 1)))),
);
const cols = Math.round((x1 - x0 + 1) / size);
const rows = Math.round((y1 - y0 + 1) / size);
const grid = [];
for (let r = 0; r < rows; r++) {
	const row = [];
	for (let c = 0; c < cols; c++) {
		const px = img.at(Math.min(x1, x0 + Math.floor((c + 0.5) * size)), Math.min(y1, y0 + Math.floor((r + 0.5) * size)));
		row.push(near(px, bg) ? null : `#${px.toString(16).padStart(6, "0")}`);
	}
	grid.push(row);
}
const target = "packages/faro/src/logo-pixels.ts";
const rowsText = grid.map((row) => `\t[${row.map((p) => (p ? `"${p}"` : "null")).join(", ")}],`).join("\n");
writeFileSync(
	target,
	`// Generated by scripts/logo.mjs from ${file}. Edit the image and run \`npm run logo\` instead of this file.
export const LOGO_PIXELS: ReadonlyArray<ReadonlyArray<string | null>> = [
${rowsText}
];
`,
);
console.log(`${file}: ${cols}x${rows} blocks of ${size}px -> ${target}`);
for (const row of grid) console.log(row.map((p) => (p ? "#" : ".")).join(""));
